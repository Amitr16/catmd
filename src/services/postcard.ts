const VOICE_RULES = `You are writing a punchy social-media caption from a cat's POV. The user will paste it onto an Instagram / TikTok post alongside a photo collage. The caption must be SHORT, QUOTABLE, and make people stop scrolling.

HARD RULES (violate any of these and the output is wrong):
- ONE sentence. Not two. Not "X. Y." — ONE.
- 12 WORDS MAXIMUM. Aim for 4-8.
- NEVER start with "Today" or any temporal opener ("This morning", "Yesterday" etc).
- NEVER write like a diary or journal entry. This is a quotable line, not a recap.
- NEVER literally describe the photo ("look at me sitting", "here I am").
- NEVER use generic adjectives ("discerning", "peculiar", "whimsical", "magical"). Specific > flowery.
- NO emojis. NO hashtags. NO capital-letter all-caps shouting.
- Cat-voice, first person. SWAG ENERGY: imperious, judgmental, slightly disdainful, smug. Confident bordering on arrogant. NEVER baby-talk, NEVER "uwu", NEVER polite, NEVER apologetic.
- FORBIDDEN PHRASES that immediately kill the voice: "I appreciate", "thank you", "I find joy", "of course", "I love", "such a", "so much". If your draft contains any of these — start over.

WHAT WORKS (calibrate to this register — do NOT copy these literally):

"Status: regal."
"The bird at the window was unreasonable."
"Won."
"Negotiated terms with the windowsill."
"We do not chase. We cause."
"Day 14 of training the human."
"The blanket and I have an understanding."
"I have decided the green chair is, finally, mine."
"Three feints, one capture. Correct pace."
"Demanded fealty. Received it."
"Supervised."
"The bath water has betrayed me."
"Reviewed the household. Verdict: tolerable."

WHAT DOES NOT WORK (these are immediate failures):

❌ "Today, I observed the world with a discerning eye, noting the peculiarities of my realm."
   → Too long, starts with "Today", journal-style, generic adjectives.
❌ "Look at this adorable photo of Mittens napping on the couch."
   → Describes the photo literally, baby-talk register.
❌ "Such a cute kitty day! 🐱✨ #catsofinstagram"
   → Emojis, hashtags, generic.
❌ "Hey friends! Just wanted to share what I've been up to today..."
   → Conversational diary opener.

Aim: an aphorism, a verdict, a deadpan observation. The kind of line someone would screenshot and send to a friend.

Output JSON with two fields:
  - "caption": ONE sentence, ≤12 words, in the cat's voice
  - "mood_word": one single word capturing today's mood (e.g. "regal", "smug", "playful", "sleepy")`;

function buildCaptionUserPrompt(opts: {
  catName: string;
  photoCount: number;
  archetype: PersonalityArchetype | null;
  hasCheckin: boolean;
  hasScan: boolean;
  hasReadCat: boolean;
  weekday: string;
  /** Most recent check-in mood (today): "happy" / "normal" / "off". */
  todaysMood?: string | null;
  /** Body language observation tags from today's Read session. */
  bodyLanguageTags?: string[];
  /**
   * Streak-day milestone hit today (7 / 14 / 30 / 60 / 90 / 180 / 365)
   * or null. Postcards on milestone days lean celebratory.
   */
  streakMilestone?: number | null;
  /** True if today is the cat's birthday. Caption may riff on it. */
  isBirthday?: boolean;
  /** True if today is the cat's adoption-iversary. */
  isAdoptionIversary?: boolean;
}): string {
  const {
    catName,
    photoCount,
    archetype,
    hasCheckin,
    hasScan,
    hasReadCat,
    weekday,
    todaysMood,
    bodyLanguageTags,
    streakMilestone,
    isBirthday,
    isAdoptionIversary,
  } = opts;

  const lines: string[] = [];
  lines.push(`Cat name: ${catName}.`);
  lines.push(`Today is ${weekday}.`);
  lines.push(`Number of photos in today's collage: ${photoCount}.`);

  if (archetype) {
    const meta = ARCHETYPE_META[archetype];
    lines.push(`Personality archetype: ${meta.name} — ${meta.oneLiner}`);
  }

  if (todaysMood) {
    lines.push(`Today's check-in mood: ${todaysMood}.`);
  }

  if (bodyLanguageTags && bodyLanguageTags.length > 0) {
    // Cap so the prompt doesn't bloat from a chatty observation.
    const capped = bodyLanguageTags.slice(0, 5).join(', ');
    lines.push(`Body language tags from today's Read session: ${capped}.`);
  }

  if (isBirthday) {
    lines.push(`SPECIAL: today is ${catName}'s BIRTHDAY. The caption may lean celebratory but stay quotable.`);
  } else if (isAdoptionIversary) {
    lines.push(`SPECIAL: today is the anniversary of when ${catName} joined the household. Lean reflective + warm.`);
  } else if (streakMilestone) {
    lines.push(`SPECIAL: ${streakMilestone}-day check-in streak landed today. The caption may acknowledge the rhythm — "day ${streakMilestone}" energy.`);
  }

  const dayBits: string[] = [];
  if (hasCheckin) dayBits.push('a daily check-in was logged');
  if (hasScan) dayBits.push('a triage scan was run');
  if (hasReadCat) dayBits.push(`a body-language read was recorded`);
  if (dayBits.length > 0) {
    lines.push(`Notable events today: ${dayBits.join(', ')}.`);
  }

  lines.push('');
  lines.push('Write the caption. JSON only.');

  return lines.join('\n');
}

