/**
 * Read a local file:// URI as base64. Best-effort — returns null on any
 * failure so the caption still generates without the photo reference.
 */
async function fileUriToBase64(uri: string | null | undefined): Promise<string | null> {
  if (!uri) return null;
  if (!uri.startsWith('file://') && !uri.startsWith('/')) return null;
  try {
    return await FileSystem.readAsStringAsync(uri, {
      encoding: FileSystem.EncodingType.Base64,
    });
  } catch {
    return null;
  }
}

const WEEKDAYS = [
  'Sunday',
  'Monday',
  'Tuesday',
  'Wednesday',
  'Thursday',
  'Friday',
  'Saturday',
];

/**
 * Generate today's postcard for the cat. Pulls together the day's
 * photos + an AI-generated short caption. The caller is responsible
 * for surfacing the result + the editable caption field.
 *
 * Throws on AI errors — caller catches and shows a retry CTA.
 */
export async function generatePostcard(opts: {
  cat: CatProfile;
  photos: PostcardPhoto[];
  archetype: PersonalityArchetype | null;
  hasCheckinToday: boolean;
  hasScanToday: boolean;
  hasReadCatToday: boolean;
  /** Today's most-recent check-in mood word ("happy" / "normal" / "off"). */
  todaysMood?: string | null;
  /** Body-language observation tags from today's Read session, if any. */
  bodyLanguageTags?: string[];
  /** Streak milestone landed today (7 / 14 / 30 / 60 / 90 / 180 / 365). */
  streakMilestone?: number | null;
  /** True if today is the cat's birthday. */
  isBirthday?: boolean;
  /** True if today is the adoption-iversary. */
  isAdoptionIversary?: boolean;
}): Promise<Postcard> {
  const {
    cat,
    photos,
    archetype,
    hasCheckinToday,
    hasScanToday,
    hasReadCatToday,
    todaysMood,
    bodyLanguageTags,
    streakMilestone,
    isBirthday,
    isAdoptionIversary,
  } = opts;

  const today = new Date();
  const weekday = WEEKDAYS[today.getDay()] ?? 'Today';

  // Vision: attach the first photo if available so the model has SOME
  // sense of the day's visual mood. Best-effort — fall through if the
  // base64 read fails.
  const referenceBase64 = photos.length > 0 ? await fileUriToBase64(photos[0]?.uri) : null;

  const user = buildCaptionUserPrompt({
    catName: cat.name,
    photoCount: photos.length,
    archetype,
    hasCheckin: hasCheckinToday,
    hasScan: hasScanToday,
    hasReadCat: hasReadCatToday,
    weekday,
    ...(todaysMood !== undefined ? { todaysMood } : {}),
    ...(bodyLanguageTags ? { bodyLanguageTags } : {}),
    ...(streakMilestone !== undefined ? { streakMilestone } : {}),
    ...(isBirthday !== undefined ? { isBirthday } : {}),
    ...(isAdoptionIversary !== undefined ? { isAdoptionIversary } : {}),
  });

  type LlmResult = { caption: string; mood_word: string };

  const result = await completeJson<LlmResult>({
    activity: 'postcard_caption',
    system: VOICE_RULES,
    user,
    imageBase64: referenceBase64,
    imageDetail: 'low',
    temperature: 0.8,    // higher than diary's 0.85 isn't safe (long output);
                         // 0.8 keeps output punchy + lets the model find a
                         // surprising aphoristic angle vs returning the same
                         // safe phrasing every time.
    maxTokens: 80,       // hard ceiling so the model can't write a paragraph
                         // even if it wanted to. 12-word caption ≈ 30 tokens
                         // + JSON wrapper + mood_word ≈ 50 tokens; 80 has
                         // headroom but blocks essay-length drift.
    jsonSchema: {
      name: 'cat_postcard_caption',
      strict: true,
      schema: {
        type: 'object',
        additionalProperties: false,
        required: ['caption', 'mood_word'],
        properties: {
          caption: { type: 'string' },
          mood_word: { type: 'string' },
        },
      },
    },
  });

  const caption = result.caption.trim();
  const moodWord = (result.mood_word ?? '').trim().toLowerCase() || undefined;

  return {
    id: `pc_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`,
    cat_id: cat.id,
    date: localDateKey(today),
    caption,
    caption_ai_original: caption,
    photos,
    generated_at: new Date().toISOString(),
    model: process.env.EXPO_PUBLIC_AI_MODEL ?? 'gpt-4o-mini',
    caption_prompt_version: POSTCARD_CAPTION_PROMPT_VERSION,
    ...(moodWord ? { mood_word: moodWord } : {}),
  };
}

/** Date key helper for store cache keys. */
export function todayKey(): string {
  return localDateKey(new Date());
}
