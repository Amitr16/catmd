/**
 * Postcard service — daily social-format capture-card.
 *
 * Sibling to the Diary feature, deliberately split. Diary = long-form,
 * private, reflective journal entries. Postcard = short, public,
 * photo-first social card the user can edit + share to
 * Instagram / TikTok / Twitter.
 *
 * What a Postcard is:
 *   - 2-4 of TODAY's photos arranged in a collage
 *   - 1-2 line caption in the cat's voice (editable by the user)
 *   - Tasteful "🐾 catmd.pet" watermark in a corner
 *   - Captured as 1080×1080 (square) or 1080×1920 (story) PNG
 *   - Shared via the native share sheet
 *
 * Photo sources for the collage (today's local-date window):
 *   - The cat profile photo IF updated today
 *   - Scan image_uri from any scan run today
 *   - symptom_photo health events from today
 *   (Diary's photoUri is NOT used here — diary is text-only now.)
 *
 * Caption generation: same LLM stack as diary but with a TIGHTLY
 * constrained prompt (1-2 sentences max, must read as a quotable
 * Instagram caption, must work standalone without the diary's
 * extended cat-voice context).
 *
 * Cost: ~$0.0002 per caption. Trivial.
 */
