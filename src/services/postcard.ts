/** A single photo entry in the postcard collage. */
export type PostcardPhoto = {
  /** Local file:// URI on the device. */
  uri: string;
  /**
   * Where this photo came from — surfaced in analytics + future UX.
   * `gallery` is the new canonical source (Bond's hero photo capture).
   * `profile` covers the legacy fallback for cats whose photo was
   * uploaded before the gallery existed AND was the only thing
   * available for the postcard. `scan` / `symptom_photo` are kept as
   * type variants but no longer populated by `gatherTodaysPhotos` — they
   * exist so old cached postcards still type-check.
   */
  source: 'gallery' | 'profile' | 'scan' | 'symptom_photo';
  /** ISO timestamp the photo was attached/captured. */
  captured_at: string;
  /**
   * Pixel dimensions of the original photo. Used by the collage layout
   * picker to match each photo to a cell with a similar aspect ratio
   * (so we tile 3 portraits as 3 columns, 3 landscapes as 3 stripes,
   * 1 landscape + 2 portraits as a wide-top + split-bottom layout, etc.)
   * — and to pick `cover` vs `contain` per cell so we minimise the
   * dark blurred-backdrop fill that Android's captureRef rendered too
   * dark on share. Optional because old cached postcards don't have it
   * (they fall back to the legacy 3-stripe layout, which is fine — the
   * day they're regenerated with v3+ they'll get the new tiling).
   */
  width?: number;
  height?: number;
};

export type Postcard = {
  id: string;
  cat_id: string;
  date: string;          // YYYY-MM-DD local
  caption: string;       // editable; starts as AI-generated
  caption_ai_original: string; // the original AI version (for "reset to AI" UX + funnel signal)
  photos: PostcardPhoto[];
  generated_at: string;
  model: string;
  /**
   * Single mood word produced by the captioner (e.g. "regal", "smug",
   * "playful", "sleepy"). Used for matching trending-audio suggestions
   * in the share flow. Optional because postcards generated before this
   * field landed don't have it.
   */
  mood_word?: string;
  /**
   * Prompt version that produced this caption. Used to silently
   * migrate stale postcards on Postcard screen mount — captions
   * generated by the v1 prompt are long and journal-style ("Today, I
   * observed the world..."), which the v2 prompt (2026-05-02) forbids.
   * Bumping this number triggers a one-shot auto-regen on next view.
   *
   *   1 = original prompt (long, "Today, I..." failures common)
   *   2 = 2026-05-02 prompt (≤12 words, no temporal openers)
   *
   * Postcards with `undefined` are treated as v1.
   */
  caption_prompt_version?: number;
};

/** The current postcard caption prompt version. Bump on every prompt
 *  rewrite so cached postcards auto-migrate on next view. */
export const POSTCARD_CAPTION_PROMPT_VERSION = 3;

